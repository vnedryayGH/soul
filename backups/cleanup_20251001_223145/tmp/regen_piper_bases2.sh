set -euo pipefail
export ESPEAK_DATA_PATH=/usr/local/share/espeak-ng-data
PIPER=/usr/local/bin/piper
OUT=/opt/piper_personas_fix2
mkdir -p "$OUT"/Soul "$OUT"/Ved "$OUT"/FR_Ranevskaya
# texts (~12-15s)
TS='?  ????. ??????, ???????? ?????. ????????? ????????? ?????????. ?????? ??????????, ? ???????, ??? ??????, ?????? ? ?????.'
TV='?  ???. ?????? ??????? ? ??????????? ????. ????????? ???? ???????, ??? ? ??????? ????. ?????? ????? ?????? ????? ? ????.'
TR='?  ????? ?????????. ????? ?????? ? ?? ???????, ? ?????? ????????? ? ???????. ?????? ???????????, ?? ????????????.'
M_RUS=/opt/piper/models/ru_RU-ruslan-medium.onnx; C_RUS=/opt/piper/models/ru_RU-ruslan-medium.onnx.json
M_DMI=/opt/piper/models/ru_RU-dmitri-medium.onnx; C_DMI=/opt/piper/models/ru_RU-dmitri-medium.onnx.json
M_IRI=/opt/piper/models/ru_RU-irina-medium.onnx;  C_IRI=/opt/piper/models/ru_RU-irina-medium.onnx.json
# synth with slower pace
printf "%s\n" "$TS" | "$PIPER" --espeak_data "$ESPEAK_DATA_PATH" --length_scale 1.6 -m "$M_RUS" -c "$C_RUS" -f "$OUT/Soul/01_base_ruslan.wav"
printf "%s\n" "$TV" | "$PIPER" --espeak_data "$ESPEAK_DATA_PATH" --length_scale 1.5 -m "$M_DMI" -c "$C_DMI" -f "$OUT/Ved/01_base_dmitri.wav"
printf "%s\n" "$TR" | "$PIPER" --espeak_data "$ESPEAK_DATA_PATH" --length_scale 1.6 -m "$M_IRI" -c "$C_IRI" -f "$OUT/FR_Ranevskaya/01_base_irina.wav"
# ensure 48kHz mono
ffmpeg -y -loglevel error -i "$OUT/Soul/01_base_ruslan.wav" -ar 48000 -ac 1 "$OUT/Soul/01_base_ruslan_48k.wav" && mv -f "$OUT/Soul/01_base_ruslan_48k.wav" "$OUT/Soul/01_base_ruslan.wav"
ffmpeg -y -loglevel error -i "$OUT/Ved/01_base_dmitri.wav" -ar 48000 -ac 1 "$OUT/Ved/01_base_dmitri_48k.wav" && mv -f "$OUT/Ved/01_base_dmitri_48k.wav" "$OUT/Ved/01_base_dmitri.wav"
ffmpeg -y -loglevel error -i "$OUT/FR_Ranevskaya/01_base_irina.wav" -ar 48000 -ac 1 "$OUT/FR_Ranevskaya/01_base_irina_48k.wav" && mv -f "$OUT/FR_Ranevskaya/01_base_irina_48k.wav" "$OUT/FR_Ranevskaya/01_base_irina.wav"
# durations
ffprobe -v error -show_entries format=filename,duration -of default=noprint_wrappers=1:nokey=0 "$OUT/Soul/01_base_ruslan.wav" "$OUT/Ved/01_base_dmitri.wav" "$OUT/FR_Ranevskaya/01_base_irina.wav" | sed -n '1,20p'
cd "$OUT" && tar -czf piper_personas_base_fix2.tar.gz Soul Ved FR_Ranevskaya && ls -l piper_personas_base_fix2.tar.gz