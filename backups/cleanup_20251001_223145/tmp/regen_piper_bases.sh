set -euo pipefail
export ESPEAK_DATA_PATH=/usr/local/share/espeak-ng-data
PIPER=/usr/local/bin/piper
OUT=/opt/piper_personas_fix
mkdir -p "$OUT"/Soul "$OUT"/Ved "$OUT"/FR_Ranevskaya
# Prepare UTF-8 texts (~12-15 sec)
cat > /root/piper_txt_soul.txt << 'TXT'
?  ????. ??????, ???????? ?????. ????????? ????????? ?????????, ????????? ??????.
?????? ??????????, ? ???????, ??? ??????, ?????? ? ?????.
TXT
cat > /root/piper_txt_ved.txt << 'TXT'
?  ???. ?????? ??????? ? ??????????? ????. ????????? ???? ???????, ??? ? ??????? ????.
?????? ????? ?????? ????? ? ????, ? ?????? ????????????.
TXT
cat > /root/piper_txt_ran.txt << 'TXT'
?  ????? ?????????. ????? ?????? ? ?? ???????, ? ?????? ????????? ? ???????.
? ?????? ???????????, ?? ????????????, ???????? ???????????? ???????.
TXT
# Models
M_RUS=/opt/piper/models/ru_RU-ruslan-medium.onnx; C_RUS=/opt/piper/models/ru_RU-ruslan-medium.onnx.json
M_DMI=/opt/piper/models/ru_RU-dmitri-medium.onnx; C_DMI=/opt/piper/models/ru_RU-dmitri-medium.onnx.json
M_IRI=/opt/piper/models/ru_RU-irina-medium.onnx;  C_IRI=/opt/piper/models/ru_RU-irina-medium.onnx.json
# Synthesize base wavs reading from UTF-8 files
LC_ALL=C.UTF-8 "$PIPER" --espeak_data "$ESPEAK_DATA_PATH" -m "$M_RUS" -c "$C_RUS" -f "$OUT/Soul/01_base_ruslan.wav" < /root/piper_txt_soul.txt
LC_ALL=C.UTF-8 "$PIPER" --espeak_data "$ESPEAK_DATA_PATH" -m "$M_DMI" -c "$C_DMI" -f "$OUT/Ved/01_base_dmitri.wav" < /root/piper_txt_ved.txt
LC_ALL=C.UTF-8 "$PIPER" --espeak_data "$ESPEAK_DATA_PATH" -m "$M_IRI" -c "$C_IRI" -f "$OUT/FR_Ranevskaya/01_base_irina.wav" < /root/piper_txt_ran.txt
# Verify durations with soxi or ffprobe
ffprobe -v error -show_entries format=filename,duration -of default=noprint_wrappers=1:nokey=0 "$OUT/Soul/01_base_ruslan.wav" "$OUT/Ved/01_base_dmitri.wav" "$OUT/FR_Ranevskaya/01_base_irina.wav" | sed -n '1,20p'
cd "$OUT" && tar -czf piper_personas_base_fix.tar.gz Soul Ved FR_Ranevskaya && ls -l piper_personas_base_fix.tar.gz